"""ASR consistency diagnostic for the three labeled central-12s arms."""
from __future__ import annotations

import csv
import hashlib
import json
import re
import time
from pathlib import Path

import soundfile as sf
import torch
import whisper


ROOT = Path(__file__).resolve().parent
CACHE = Path("/data/.rootcache/whisper")
MODEL_NAME = "tiny.en"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
ARMS = ("y_pre", "off", "router")


def norm(text: str) -> list[str]:
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip().split()


def edit_distance(a: list[str], b: list[str]) -> int:
    prev = list(range(len(b) + 1))
    for i, x in enumerate(a, 1):
        cur = [i]
        for j, y in enumerate(b, 1):
            cur.append(min(cur[-1] + 1, prev[j] + 1, prev[j - 1] + (x != y)))
        prev = cur
    return prev[-1]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    manifest = list(csv.DictReader((ROOT / "manifest.csv").open(encoding="utf-8")))
    clean_ref = json.loads((ROOT / "clean_center12s_asr_reference.json").read_text(encoding="utf-8"))
    clean_by_index = {r["index"]: r for r in clean_ref["rows"]}
    model_path = CACHE / f"{MODEL_NAME}.pt"
    model = whisper.load_model(MODEL_NAME, device=DEVICE, download_root=str(CACHE))
    out_rows = []
    started = time.time()
    for row in manifest:
        idx = row["index"]
        clean_tokens = norm(clean_by_index[idx]["text"])
        arm_transcripts = {}
        arm_meta = {}
        for arm in ARMS:
            clip = next((ROOT / "listening_pack" / "simple").glob(f"{int(idx):02d}_{ {'y_pre':'Y_pre','off':'Router-off','router':'Router'}[arm]}.wav"))
            wav, sr = sf.read(clip, always_2d=False)
            if sr != 16000 or wav.ndim != 1:
                raise ValueError(f"invalid listening clip {clip}: sr={sr}, shape={getattr(wav, 'shape', None)}")
            t0 = time.time()
            result = model.transcribe(
                wav.astype("float32"), language="en", task="transcribe", temperature=0,
                beam_size=1, best_of=1, condition_on_previous_text=False,
                fp16=(DEVICE == "cuda"), verbose=False,
            )
            text = result.get("text", "").strip()
            arm_transcripts[arm] = text
            arm_meta[arm] = {
                "clip": str(clip.relative_to(ROOT)),
                "clip_sha256": sha256(clip),
                "runtime_seconds": time.time() - t0,
                "normalized_edit_distance_to_clean_asr": edit_distance(norm(text), clean_tokens) / max(1, len(clean_tokens)),
            }
        out_rows.append({"index": idx, "speaker": row["speaker"], "snr_db": row["snr_db"], "clean_asr": clean_by_index[idx]["text"], "arms": arm_transcripts, "arm_meta": arm_meta})
        print(json.dumps({"index": idx, "ned": {a: arm_meta[a]["normalized_edit_distance_to_clean_asr"] for a in ARMS}}, ensure_ascii=False), flush=True)

    out = {
        "experiment_id": "p8_frontend_backend_audit_20261020",
        "purpose": "ASR consistency diagnostic, not ground-truth WER",
        "interpretation": "All text is generated by the same Whisper tiny.en decoder; clean is an ASR pseudo-reference. Use only to prioritize listening.",
        "model": {"name": MODEL_NAME, "sha256": sha256(model_path), "path": str(model_path), "device": DEVICE, "whisper_version": getattr(whisper, "__version__", "unknown")},
        "n": len(out_rows), "runtime_seconds": time.time() - started, "rows": out_rows,
    }
    (ROOT / "arms_center12s_asr_diagnostic.json").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["# 三臂中央 12 秒 ASR 辅助对照", "", "同一个 Whisper tiny.en 对 clean/Y_pre/Router-off/Router 解码。clean 也是 ASR 伪参考，以下不能当作真实 WER，只用于发现需要重点听的样本。", ""]
    for r in out_rows:
        lines += [f"## 样本 {r['index']}（SNR {r['snr_db']} dB）", "", f"**clean 参考：** {r['clean_asr']}", ""]
        for arm in ARMS:
            lines += [f"**{arm}：** {r['arms'][arm]}", f"- 相对 clean ASR 的归一化编辑距离：{r['arm_meta'][arm]['normalized_edit_distance_to_clean_asr']:.3f}", ""]
    (ROOT / "arms_center12s_asr_diagnostic.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
