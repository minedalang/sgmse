#!/usr/bin/env python
"""Create paper-ready LaTeX tables from the frozen evaluation JSON."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = Path("/data/coding/sgmse")
BOOT = ROOT / "experiments/final_eval_full_20261018/metrics/paired_bootstrap.pretty.json"
INTER = ROOT / "experiments/final_eval_reverb_interaction_20261018_metrics.json"
OUT = HERE / "paper_tables.tex"
META = HERE / "table_metadata.json"

METRICS = [
    ("PESQ_e", "PESQ"),
    ("STOI_e", "STOI"),
    ("SI-SDR_e", "SI-SDR (dB)"),
    ("DNSMOS_SIG_e", "DNSMOS-SIG"),
    ("DNSMOS_OVRL_e", "DNSMOS-OVRL"),
    ("DNSMOS_P808_e", "DNSMOS-P808"),
    ("DNSMOS_BAK_e", "DNSMOS-BAK"),
]


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def signed(x: float, digits: int = 4) -> str:
    return f"{x:+.{digits}f}"


def ci(item, digits: int = 4) -> str:
    return f"{signed(item['mean_delta'], digits)} [{signed(item['ci95'][0], digits)}, {signed(item['ci95'][1], digits)}]"


def main():
    boot = json.loads(BOOT.read_text())
    inter = json.loads(INTER.read_text())
    lines = [
        "% Auto-generated by make_tables.py from frozen final-evaluation outputs.",
        "% Do not edit numeric values manually; rerun the script instead.",
        "",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Pooled paired results on the locked 300-utterance evaluation. Values in the delta columns are mean changes relative to the Router-off arm; intervals are 95\% utterance bootstrap CIs.}",
        r"\label{tab:final-pooled}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Metric & Router-off mean & Router $-$ off & $t_{\mathrm{cut}}=0.05$ $-$ off \\",
        r"\midrule",
    ]
    for key, label in METRICS:
        off = boot["arms"]["off"][key]
        lines.append(f"{label} & {off:.4f} & {ci(boot['router_vs_off'][key])} & {ci(boot['tcut005_vs_off'][key])} \\\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Router and fixed early-time cutoff deltas by official test split. All entries are paired means relative to Router-off; the split contains 150 utterances.}",
        r"\label{tab:split-deltas}",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Metric & Router/no-reverb & Router/with-reverb & $t_{\mathrm{cut}}$/no-reverb & $t_{\mathrm{cut}}$/with-reverb \\",
        r"\midrule",
    ]
    for key, label in METRICS:
        vals = []
        for split in ["no_reverb", "with_reverb"]:
            vals.append(boot["splits"][split]["router_vs_off"][key]["mean_delta"])
        for split in ["no_reverb", "with_reverb"]:
            vals.append(boot["splits"][split]["tcut005_vs_off"][key]["mean_delta"])
        digits = 3 if key == "SI-SDR_e" else 4
        lines.append(f"{label} & {signed(vals[0], digits)} & {signed(vals[1], digits)} & {signed(vals[2], digits)} & {signed(vals[3], digits)} \\\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Matched-file interaction between reverberation and the Router effect.}",
        r"\label{tab:reverb-interaction}",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Metric & Interaction & 95\% CI \\",
        r"\midrule",
    ]
    for key, label in METRICS:
        item = inter["router_interaction_vs_off"][key]
        digits = 3 if key == "SI-SDR_e" else 4
        lines.append(f"{label} & {signed(item['mean'], digits)} & [{signed(item['ci95'][0], digits)}, {signed(item['ci95'][1], digits)}] \\\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\begin{flushleft}",
        r"\footnotesize Interaction is $(\mathrm{Router}-\mathrm{off})_{\mathrm{with}}-(\mathrm{Router}-\mathrm{off})_{\mathrm{without}}$; bootstrap unit is matched file ID.",
        r"\end{flushleft}",
        r"\end{table}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    META.write_text(
        json.dumps(
            {
                "source_bootstrap": str(BOOT),
                "source_bootstrap_sha256": sha(BOOT),
                "source_interaction": str(INTER),
                "source_interaction_sha256": sha(INTER),
                "test_set_tuning": False,
                "audio_regenerated": False,
                "dataset_modified": False,
                "checkpoint_modified": False,
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
